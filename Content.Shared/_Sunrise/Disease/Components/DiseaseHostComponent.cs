/// <summary>
/// Тот, кто умеет болеть: зараза берётся на него извне — воздухом, касанием, едой или уколом.
/// </summary>
/// <remarks>
/// Стоит на органических гуманоидных видах и на подопытных животных вирусологии — обезьянах
/// и кобольдах. Прочее зверьё болезни не берёт: эпидемия среди мышей и карпов на раунд не влияет,
/// а каждого заболевшего моба пришлось бы обсчитывать в прогрессии болезней и симптомов.
/// Зверью-переносчику компонент не нужен: компонент заражения ударом болезнь
/// не обсчитывает, а только передаёт ударом. Прямое заражение — зомби, админская команда,
/// стартовая болезнь от черты — компонент не проверяет: там болезнь ставится умышленно.
/// Висит в shared только ради загрузки прототипов на клиенте, проверка серверная.
/// </remarks>
