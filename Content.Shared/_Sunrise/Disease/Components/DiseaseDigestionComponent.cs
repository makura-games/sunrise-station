namespace Content.Shared._Sunrise.Disease.Components;

/// <summary>
/// Желудок, который справляется с заразой в привычной для него пище.
/// </summary>
/// <remarks>
/// Работает только с той едой, что проходит по <c>SpecialDigestible</c> самого желудка:
/// рептилоид переварит личинок вместе с сырым мясом, а человек от того же стейка слёг бы.
/// Висит на базовом прототипе желудка, поэтому новый вид получает поведение сам,
/// а в своём прототипе органа может задать множитель иначе.
/// Логика серверная, в shared лежит ради загрузки прототипов на клиенте.
/// </remarks>
[RegisterComponent]
public sealed partial class DiseaseDigestionComponent : Component
{
    /// <summary>
    /// Во сколько раз реже владелец заражается от привычной ему пищи.
    /// Единица — пищеварение не помогает вовсе, ноль — полный иммунитет.
    /// </summary>
    /// <remarks>
    /// Множитель, а не иммунитет: пищеварение справляется чаще обычного, но заразу не стерилизует,
    /// да и шанс бросается на каждый укус. Действует только на пищевой путь: от капель и касаний
    /// желудок не спасает, даже если болезнь грибковая или паразитическая.
    /// </remarks>
    [DataField]
    public float Multiplier = 0.3f;
}
