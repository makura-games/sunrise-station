namespace Content.Shared._Sunrise.Disease.Analysis;

/// <summary>
/// Насколько глубоко анализ образца раскрывает болезнь. Каждый уровень включает всё с предыдущих.
/// Настоящее название болезни не раскрывает ни один уровень.
/// </summary>
public enum DiseaseAnalysisLevel : byte
{
    /// <summary>
    /// Наблюдаемый синдром и симптомы, проявившиеся у носителя, с которого взят образец.
    /// </summary>
    Syndrome,

    /// <summary>
    /// Добавляет класс возбудителя.
    /// </summary>
    Classification,

    /// <summary>
    /// Добавляет код штамма, стадию и подсказки по лечению. Код штамма одинаков у всех носителей,
    /// поэтому образцы с разными симптомами можно связать в одну болезнь.
    /// </summary>
    Exact,
}
