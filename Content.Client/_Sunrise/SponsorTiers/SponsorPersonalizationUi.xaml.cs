namespace Content.Client._Sunrise.SponsorTiers;

[GenerateTypedNameReferences]
public sealed partial class SponsorPersonalizationUi : FancyWindow
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private ILocalizationManager _loc = default!;
    [Dependency] private IPlayerManager _player = default!;
    [Dependency] private IClientAdminManager _adminManager = default!;
    [Dependency] private IEntityManager _entityManager = default!;
    private readonly ISharedSponsorsManager? _sponsorsManager;

    private readonly Dictionary<Button, string> _colorButtons = new();

    private const string NoneToken = "@none";
    private const string PreviewAccentColor = "#00e5ff";
    private const string AdminHelpColor = "#ff0000";
    private const string AdminColor = "#800080";
    private static readonly Color DefaultBorderColor = Color.FromHex("#2e2e38");
    private static readonly Color DisabledBorderColor = Color.FromHex("#25252b");
    private static readonly Color PanelBackgroundColor = Color.FromHex("#111115");
    private static readonly Color PanelHoverBackgroundColor = Color.FromHex("#16161c");
    private static readonly Color DefaultHoverBorderColor = Color.FromHex("#1e1e24");

    private static readonly Type[] AllowedTags =
    [
        typeof(BoldTag),
        typeof(ItalicTag),
        typeof(ColorTag),
        typeof(EmojiTag)
    ];

    private List<string> _allowedTitles = [];


    private readonly ButtonGroup _titleGroup = new();
    private readonly ButtonGroup _colorGroup = new();

    private EmojiPickerWindow? _emojiPicker;

    public SponsorPersonalizationUi()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        IoCManager.Instance!.TryResolveType(out _sponsorsManager);

        ChooseEmojiButton.OnPressed += _ => OpenEmojiPicker();
        ResetEmojiButton.OnPressed += _ => ResetEmoji();

        UpdateUiState();

        LobbyTtsCheckBox.OnToggled += OnLobbyTtsToggled;
    }

    private void UpdateUiState()
    {
        if (_sponsorsManager == null)
            return;

        var localPlayer = _player.LocalSession;

        var allowedLobbyTts = _sponsorsManager.ClientAllowedLobbyTts();
        LobbyTtsCheckBox.Visible = allowedLobbyTts;
        if (allowedLobbyTts)
        {
            LobbyTtsCheckBox.Pressed = _cfg.GetCVar(SunriseCCVars.SponsorLobbyTtsEnabled);
        }

        var isAdminActive = _adminManager.IsActive();
        var adminData = _adminManager.GetAdminData();
        var isSponsor = _sponsorsManager.ClientIsSponsor();
        var isAllowedAdminBypass = isAdminActive && isSponsor;

        var hasEmojiRights = (localPlayer != null && _sponsorsManager.IsAllowedOocTitleEmoji(localPlayer.UserId)) || isAllowedAdminBypass;
        EmojiSectionPanel.Visible = hasEmojiRights;
        if (hasEmojiRights)
        {
            var currentEmoji = _cfg.GetCVar(SunriseCCVars.SponsorOocEmoji);
            if (string.IsNullOrEmpty(currentEmoji))
            {
                SelectedEmojiLabel.SetMessage(FormattedMessage.FromMarkupOrThrow($"[color=gray]{Loc.GetString("sponsor-personalization-none-emoji")}[/color]"), AllowedTags);
            }
            else
            {
                var emojiId = currentEmoji.Trim(':');
                SelectedEmojiLabel.SetMessage(FormattedMessage.FromMarkupOrThrow($"[emoji id=\"{emojiId}\" size=50]"), AllowedTags);
            }
        }

        var currentTitle = _cfg.GetCVar(SunriseCCVars.SponsorOocTitle);
        var activeTitle = currentTitle;
        if (string.IsNullOrEmpty(activeTitle) && localPlayer != null)
        {
            _sponsorsManager.TryGetOocTitle(localPlayer.UserId, out activeTitle);
        }

        _allowedTitles = _sponsorsManager.GetAllowedOocTitles();
        TitlesGrid.DisposeAllChildren();

        var noneTitleBtn = new Button
        {
            Text = Loc.GetString("sponsor-personalization-none-title"),
            ToggleMode = true,
            Group = _titleGroup,
            Pressed = currentTitle == NoneToken || (string.IsNullOrEmpty(currentTitle) && !_sponsorsManager.ClientIsSponsor()),
            HorizontalExpand = true
        };
        noneTitleBtn.OnPressed += _ => OnTitlePressed(NoneToken);
        TitlesGrid.AddChild(noneTitleBtn);

        foreach (var title in _allowedTitles)
        {
            if (!OocGradientHelper.TryResolveTitle(title, out var resolvedTitle))
                continue;

            var titleBtn = new Button
            {
                Text = resolvedTitle,
                ToggleMode = true,
                Group = _titleGroup,
                Pressed = title == activeTitle,
                HorizontalExpand = true
            };
            var t = title;
            titleBtn.OnPressed += _ => OnTitlePressed(t);
            TitlesGrid.AddChild(titleBtn);
        }

        var currentColor = _cfg.GetCVar(SunriseCCVars.SponsorOocColor);
        var activeColor = currentColor;
        if (string.IsNullOrEmpty(activeColor) && localPlayer != null)
        {
            if (_sponsorsManager.TryGetOocColor(localPlayer.UserId, out var defaultColor))
            {
                activeColor = "#" + defaultColor.Value.ToHexNoAlpha().TrimStart('#');
            }
        }

        var allColorChoices = new List<string> { NoneToken };

        var allowedGradients = _sponsorsManager.GetAllowedOocGradients();
        var allowedColors = _sponsorsManager.GetAllowedOocColors();

        allColorChoices.AddRange(allowedGradients);

        foreach (var col in allowedColors)
        {
            if (col != NoneToken && !allColorChoices.Contains(col))
                allColorChoices.Add(col);
        }

        ColorsGrid.DisposeAllChildren();
        _colorButtons.Clear();

        foreach (var colorHex in allColorChoices)
        {
            var isSelected = colorHex == activeColor || (colorHex == NoneToken && string.IsNullOrEmpty(currentColor));

            Color? parsedColor = null;
            if (colorHex != NoneToken)
            {
                if (!OocGradientHelper.TryResolveColor(colorHex, out var resolvedColor))
                    continue;
                parsedColor = resolvedColor.Value;
            }

            var colorBtn = new Button
            {
                ToggleMode = true,
                Group = _colorGroup,
                Pressed = isSelected,
                HorizontalExpand = true,
                MinHeight = 32
            };
            colorBtn.StyleClasses.Clear();
            _colorButtons[colorBtn] = colorHex;

            var label = new RichTextLabel
            {
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                MouseFilter = MouseFilterMode.Ignore
            };

            var locKey = colorHex == NoneToken ? "sponsor-personalization-none-color" : $"sponsor-personalization-color-{colorHex.ToLower()}";
            var displayName = _loc.TryGetString(locKey, out var localizedName) ? localizedName : colorHex;

            if (colorHex == NoneToken)
            {
                label.SetMessage(FormattedMessage.FromMarkupOrThrow($"[bold]{displayName}[/bold]"));
            }
            else if (OocGradientHelper.IsGradientId(colorHex))
            {
                label.SetMessage(FormattedMessage.FromMarkupOrThrow($"[bold]{OocGradientHelper.ApplyGradientById(displayName, colorHex)}[/bold]"));
            }
            else
            {
                var hexStr = parsedColor!.Value.ToHexNoAlpha().TrimStart('#');
                label.SetMessage(FormattedMessage.FromMarkupOrThrow($"[bold][color=#{hexStr}]{displayName}[/color][/bold]"));
            }

            var borderBaseColor = DefaultBorderColor;
            if (colorHex != NoneToken)
            {
                if (OocGradientHelper.IsGradientId(colorHex))
                {
                    if (OocGradientHelper.TryGetGradientColors(colorHex, out var colors) && colors.Length > 0)
                        borderBaseColor = colors[0];
                }
                else if (parsedColor != null)
                {
                    borderBaseColor = parsedColor.Value;
                }
            }

            var borderColor = isSelected ? borderBaseColor : (colorHex == NoneToken ? DisabledBorderColor : borderBaseColor.WithAlpha(0.35f));
            var borderThickness = isSelected ? 2 : 1;

            var colorPanel = new PanelContainer
            {
                PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = PanelBackgroundColor,
                    BorderThickness = new Thickness(borderThickness),
                    BorderColor = borderColor
                },
                MouseFilter = MouseFilterMode.Ignore,
                HorizontalExpand = true,
                VerticalExpand = true
            };

            colorPanel.AddChild(label);
            colorBtn.AddChild(colorPanel);

            var c = colorHex;
            var finalBaseColor = borderBaseColor;
            colorBtn.OnMouseEntered += _ =>
            {
                var isCurrentlySelected = _cfg.GetCVar(SunriseCCVars.SponsorOocColor) == c || (c == NoneToken && string.IsNullOrEmpty(_cfg.GetCVar(SunriseCCVars.SponsorOocColor)));
                colorPanel.PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = PanelHoverBackgroundColor,
                    BorderThickness = new Thickness(isCurrentlySelected ? 2 : 1.5f),
                    BorderColor = isCurrentlySelected ? finalBaseColor : (c == NoneToken ? Color.White : finalBaseColor)
                };
            };
            colorBtn.OnMouseExited += _ =>
            {
                var isCurrentlySelected = _cfg.GetCVar(SunriseCCVars.SponsorOocColor) == c || (c == NoneToken && string.IsNullOrEmpty(_cfg.GetCVar(SunriseCCVars.SponsorOocColor)));
                colorPanel.PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = PanelBackgroundColor,
                    BorderThickness = new Thickness(isCurrentlySelected ? 2 : 1),
                    BorderColor = isCurrentlySelected ? finalBaseColor : (c == NoneToken ? DisabledBorderColor : finalBaseColor.WithAlpha(0.35f))
                };
            };

            colorBtn.OnPressed += _ => OnColorPressed(c);
            ColorsGrid.AddChild(colorBtn);
        }

        UpdateColorSelectionBorders(activeColor);
        UpdateChatPreview();
    }

    private void UpdateChatPreview()
    {
        var localPlayer = _player.LocalSession;
        var playerName = localPlayer?.Name ?? "Player";

        var currentTitle = _cfg.GetCVar(SunriseCCVars.SponsorOocTitle);

        var allowedTitles = _sponsorsManager?.GetAllowedOocTitles() ?? new List<string>();
        var isAllowedTitle = currentTitle == NoneToken || string.IsNullOrEmpty(currentTitle) || allowedTitles.Contains(currentTitle);
        if (!isAllowedTitle)
        {
            _cfg.SetCVar(SunriseCCVars.SponsorOocTitle, string.Empty);
            _cfg.SaveToFile();
            currentTitle = string.Empty;
        }

        var title = string.Empty;
        if (currentTitle == NoneToken)
        {
            title = string.Empty;
        }
        else if (!string.IsNullOrEmpty(currentTitle))
        {
            if (OocGradientHelper.TryResolveTitle(currentTitle, out var resolvedTitle))
                title = resolvedTitle;
        }
        else
        {
            if (localPlayer != null)
                _sponsorsManager?.TryGetOocTitle(localPlayer.UserId, out title);
        }

        var namePart = playerName;
        var titlePart = title;

        var currentColor = _cfg.GetCVar(SunriseCCVars.SponsorOocColor);

        var allowedColors = _sponsorsManager?.GetAllowedOocColors() ?? new List<string>();
        var allowedGradients = _sponsorsManager?.GetAllowedOocGradients() ?? new List<string>();
        var isAllowedColor = currentColor == NoneToken || string.IsNullOrEmpty(currentColor) ||
                             allowedColors.Contains(currentColor) || allowedGradients.Contains(currentColor);
        if (!isAllowedColor)
        {
            _cfg.SetCVar(SunriseCCVars.SponsorOocColor, string.Empty);
            _cfg.SaveToFile();
            currentColor = string.Empty;
        }

        var isAdminActive = _adminManager.IsActive();
        var adminData = _adminManager.GetAdminData();
        var isSponsor = _sponsorsManager?.ClientIsSponsor() ?? false;
        var isAllowedAdminBypass = isAdminActive && isSponsor;
        var hasEmojiRights = (localPlayer != null && _sponsorsManager != null && _sponsorsManager.IsAllowedOocTitleEmoji(localPlayer.UserId)) || isAllowedAdminBypass;

        if (isAllowedAdminBypass && adminData != null && string.IsNullOrWhiteSpace(titlePart))
            titlePart = adminData.Title;

        var currentEmoji = _cfg.GetCVar(SunriseCCVars.SponsorOocEmoji);
        var isAllowedEmoji = string.IsNullOrEmpty(currentEmoji);
        if (!isAllowedEmoji)
        {
            if (!hasEmojiRights)
            {
                isAllowedEmoji = false;
            }
            else
            {
                var emojiId = currentEmoji.Trim(':');
                var emojiSystem = _entityManager.System<SharedEmojiSystem>();
                if (localPlayer != null)
                {
                    isAllowedEmoji = emojiSystem.IsEmojiAllowedForPlayer(emojiId, localPlayer.UserId, _sponsorsManager);
                }
            }
        }
        if (!isAllowedEmoji)
        {
            _cfg.SetCVar(SunriseCCVars.SponsorOocEmoji, string.Empty);
            _cfg.SaveToFile();
            currentEmoji = string.Empty;
        }

        if (OocGradientHelper.IsGradientId(currentColor))
        {
            namePart = OocGradientHelper.ApplyGradientById(namePart, currentColor);
            if (!string.IsNullOrWhiteSpace(titlePart))
                titlePart = OocGradientHelper.ApplyGradientById(titlePart, currentColor);
        }
        else
        {
            namePart = FormattedMessage.EscapeText(namePart);
            if (!string.IsNullOrWhiteSpace(titlePart))
                titlePart = FormattedMessage.EscapeText(titlePart);
        }

        var displayName = string.IsNullOrWhiteSpace(titlePart)
            ? namePart
            : $"\\[{titlePart}\\] {namePart}";

        if (hasEmojiRights && !string.IsNullOrWhiteSpace(currentEmoji))
        {
            var emojiId = currentEmoji.Trim(':');
            displayName = $"[emoji id=\"{emojiId}\" size=50] {displayName}";
        }

        var testMessage = Loc.GetString("sponsor-personalization-preview-text");

        string previewMarkup;
        if (!OocGradientHelper.IsGradientId(currentColor))
        {
            var colorHex = string.Empty;
            if (currentColor != NoneToken && !string.IsNullOrEmpty(currentColor))
            {
                if (OocGradientHelper.TryResolveColor(currentColor, out var resolvedColor) && resolvedColor != null)
                    colorHex = $"#{resolvedColor.Value.ToHexNoAlpha().TrimStart('#')}";
            }
            else if (string.IsNullOrEmpty(currentColor) && localPlayer != null && _sponsorsManager != null && _sponsorsManager.TryGetOocColor(localPlayer.UserId, out var defaultColor) && defaultColor != null)
            {
                colorHex = $"#{defaultColor.Value.ToHexNoAlpha().TrimStart('#')}";
            }

            if (isAllowedAdminBypass && adminData != null && (string.IsNullOrWhiteSpace(colorHex) || currentColor == NoneToken))
                colorHex = adminData.HasFlag(AdminFlags.Adminhelp) ? AdminHelpColor : AdminColor;

            previewMarkup = !string.IsNullOrWhiteSpace(colorHex)
                ? Loc.GetString("sponsor-personalization-preview-colored", ("displayName", displayName), ("message", testMessage), ("nameColor", colorHex), ("accentColor", PreviewAccentColor))
                : Loc.GetString("sponsor-personalization-preview-no-color", ("displayName", displayName), ("message", testMessage), ("accentColor", PreviewAccentColor));
        }
        else
        {
            previewMarkup = Loc.GetString("sponsor-personalization-preview-gradient", ("displayName", displayName), ("message", testMessage), ("accentColor", PreviewAccentColor));
        }

        ChatPreviewLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(previewMarkup), AllowedTags);
    }

    private void OpenEmojiPicker()
    {
        if (_emojiPicker != null)
        {
            _emojiPicker.MoveToFront();
            return;
        }

        _emojiPicker = new EmojiPickerWindow();
        _emojiPicker.OnEmojiSelected += emojiCode =>
        {
            _cfg.SetCVar(SunriseCCVars.SponsorOocEmoji, emojiCode);
            UpdateChatPreview();

            var localPlayer = _player.LocalSession;
            var isAdminActive = _adminManager.IsActive();
            var isSponsor = _sponsorsManager?.ClientIsSponsor() ?? false;
            var isAllowedAdminBypass = isAdminActive && isSponsor;

            var hasEmojiRights = (localPlayer != null && _sponsorsManager != null && _sponsorsManager.IsAllowedOocTitleEmoji(localPlayer.UserId)) || isAllowedAdminBypass;

            if (hasEmojiRights)
            {
                var emojiId = emojiCode.Trim(':');
                SelectedEmojiLabel.SetMessage(FormattedMessage.FromMarkupOrThrow($"[emoji id=\"{emojiId}\" size=50]"), AllowedTags);
            }

            _emojiPicker.Close();
        };
        _emojiPicker.OnClose += () => _emojiPicker = null;
        _emojiPicker.OpenCentered();
    }

    private void ResetEmoji()
    {
        _cfg.SetCVar(SunriseCCVars.SponsorOocEmoji, string.Empty);
        UpdateChatPreview();
        SelectedEmojiLabel.SetMessage(FormattedMessage.FromMarkupOrThrow($"[color=gray]{Loc.GetString("sponsor-personalization-none-emoji")}[/color]"), AllowedTags);
    }

    private void UpdateColorSelectionBorders(string selectedColor)
    {
        foreach (var child in ColorsGrid.Children)
        {
            if (child is not Button btn || !_colorButtons.TryGetValue(btn, out var colorHex))
                continue;

            foreach (var innerChild in btn.Children)
            {
                if (innerChild is not PanelContainer panel || panel.PanelOverride is not StyleBoxFlat styleBox)
                    continue;

                var isSelected = colorHex == selectedColor || (colorHex == NoneToken && string.IsNullOrEmpty(selectedColor));
                styleBox.BorderThickness = new Thickness(isSelected ? 3 : 1);
                styleBox.BorderColor = isSelected ? Color.White : DefaultHoverBorderColor;
            }
        }
    }

    private void OnLobbyTtsToggled(BaseButton.ButtonToggledEventArgs args)
    {
        _cfg.SetCVar(SunriseCCVars.SponsorLobbyTtsEnabled, args.Pressed);
    }

    private void OnTitlePressed(string title)
    {
        _cfg.SetCVar(SunriseCCVars.SponsorOocTitle, title);
        UpdateChatPreview();
    }

    private void OnColorPressed(string colorHex)
    {
        _cfg.SetCVar(SunriseCCVars.SponsorOocColor, colorHex);
        UpdateColorSelectionBorders(colorHex);
        UpdateChatPreview();
    }
}
