using Content.Shared._Sunrise.PlaytimeTop;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Sunrise.PlaytimeTop;

[GenerateTypedNameReferences]
public sealed partial class PlaytimeTopWidget : Control
{
    [Dependency] private PlaytimeTopManager _playtimeTopManager = default!;

    private TabType _currentTab = TabType.Online;

    public PlaytimeTopWidget()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        OnlineTabBtn.Pressed = true;
        OnlineTabBtn.OnPressed += _ => SetTab(TabType.Online);
        WeekTabBtn.OnPressed += _ => SetTab(TabType.Week);
        MonthTabBtn.OnPressed += _ => SetTab(TabType.Month);
        AllTimeTabBtn.OnPressed += _ => SetTab(TabType.AllTime);

        _playtimeTopManager.PlaytimeTopChanged += RefreshList;
        RefreshList();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _playtimeTopManager.PlaytimeTopChanged -= RefreshList;
    }

    private void SetTab(TabType tab)
    {
        _currentTab = tab;
        OnlineTabBtn.Pressed = tab == TabType.Online;
        WeekTabBtn.Pressed = tab == TabType.Week;
        MonthTabBtn.Pressed = tab == TabType.Month;
        AllTimeTabBtn.Pressed = tab == TabType.AllTime;
        RefreshList();
    }

    private void RefreshList()
    {
        EntriesList.DisposeAllChildren();

        var list = _currentTab switch
        {
            TabType.Online => _playtimeTopManager.OnlineNow,
            TabType.Week => _playtimeTopManager.ActiveWeek,
            TabType.Month => _playtimeTopManager.ActiveMonth,
            TabType.AllTime => _playtimeTopManager.AllTime,
            _ => new List<PlaytimeTopEntry>()
        };

        foreach (var entry in list)
        {
            var control = new PlaytimeEntryControl();
            control.UpdateData(entry);
            EntriesList.AddChild(control);
        }
    }

    private enum TabType
    {
        Online,
        Week,
        Month,
        AllTime
    }
}
