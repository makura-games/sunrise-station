using Content.Client.Stylesheets;
using Content.Shared._Sunrise.Disease.Components;
using Content.Shared._Sunrise.Disease.Database;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client._Sunrise.Disease.Database;

/// <summary>
/// Окно базы данных вирусов: слева список известных штаммов, справа всё, что о выбранном известно,
/// прогресс исследования и выдача лабораторного образца.
/// </summary>
/// <remarks>
/// Окно рисуется из состояния компонента консоли. Перезарядку синтезатора клиент отсчитывает
/// по локальным часам, поэтому кнопка разблокируется сама, без ответа сервера.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class DiseaseDatabaseWindow : FancyWindow
{
    /// <summary>
    /// Запрошена пробирка с образцом выбранного штамма. Передаётся индекс штамма в списке.
    /// </summary>
    public event Action<int>? OnDispensePressed;

    /// <summary>
    /// Выбранный штамм. Выбор хранится на клиенте: в состоянии приходит весь список целиком.
    /// </summary>
    private int _selected;

    /// <summary>
    /// Цвет вывода о найденном рецепте.
    /// </summary>
    private static readonly Color RecipeKnownColor = new(90, 200, 100);

    /// <summary>
    /// Цвет вывода о том, что вакцины против штамма ещё нет.
    /// </summary>
    private static readonly Color RecipeUnknownColor = new(220, 80, 80);

    private readonly IGameTiming _timing;

    private Entity<DiseaseDatabaseConsoleComponent>? _console;

    public DiseaseDatabaseWindow()
    {
        RobustXamlLoader.Load(this);

        _timing = IoCManager.Resolve<IGameTiming>();
        DispenseButton.OnPressed += _ => OnDispensePressed?.Invoke(_selected);
    }

    public void UpdateState(Entity<DiseaseDatabaseConsoleComponent> console)
    {
        _console = console;

        var comp = console.Comp;
        if (_selected >= comp.Entries.Count)
            _selected = 0;

        UpdateStrainList(comp);
        UpdateDetails(comp);
        UpdateDispense(comp);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // Перезарядка истекает по локальным часам: кнопка оживает сама, не дожидаясь сервера.
        if (_console is { } console)
            UpdateDispense(console.Comp);
    }

    private void UpdateStrainList(DiseaseDatabaseConsoleComponent comp)
    {
        StrainContainer.RemoveAllChildren();

        for (var i = 0; i < comp.Entries.Count; i++)
        {
            var index = i;
            var entry = comp.Entries[i];

            var button = new Button
            {
                Text = Loc.GetString("disease-database-ui-strain-button", ("strain", entry.StrainCode)),
                StyleClasses = { StyleClass.ButtonSquare },
                HorizontalExpand = true,
                ToggleMode = true,
                Pressed = index == _selected,
            };
            button.OnPressed += _ =>
            {
                _selected = index;
                if (_console is { } console)
                    UpdateState(console);
            };

            StrainContainer.AddChild(button);
        }
    }

    private void UpdateDetails(DiseaseDatabaseConsoleComponent comp)
    {
        SymptomContainer.RemoveAllChildren();

        if (comp.Entries.Count == 0)
        {
            DetailsBlock.Visible = false;
            StrainLabel.Text = Loc.GetString("disease-database-ui-empty");
            return;
        }

        DetailsBlock.Visible = true;
        var entry = comp.Entries[_selected];

        StrainLabel.Text = Loc.GetString("disease-database-ui-strain", ("strain", entry.StrainCode));
        SyndromeLabel.Text = Loc.GetString("disease-database-ui-syndrome", ("syndrome", Loc.GetString(entry.Syndrome)));

        ClassLabel.Text = entry.Classification is { } classification
            ? Loc.GetString("disease-database-ui-class", ("class", Loc.GetString(classification)))
            : Loc.GetString("disease-database-ui-class-unknown");

        if (entry.Symptoms.Count == 0)
        {
            SymptomContainer.AddChild(new Label
            {
                Text = Loc.GetString("disease-database-ui-symptoms-none"),
                StyleClasses = { "LabelSubText" },
            });
        }
        else
        {
            foreach (var symptom in entry.Symptoms)
            {
                SymptomContainer.AddChild(new Label { Text = $"• {Loc.GetString(symptom)}" });
            }
        }

        UpdateResearch(entry);

        RecipeLabel.Text = Loc.GetString(entry.Solved
            ? "disease-database-ui-recipe-known"
            : "disease-database-ui-recipe-unknown");
        RecipeLabel.ModulateSelfOverride = entry.Solved ? RecipeKnownColor : RecipeUnknownColor;
    }

    /// <summary>
    /// Обновляет кнопку выдачи по времени перезарядки.
    /// </summary>
    /// <remarks>
    /// Зовётся каждый кадр, поэтому здесь только текст и флаг: списки тут не пересобираются.
    /// </remarks>
    private void UpdateDispense(DiseaseDatabaseConsoleComponent comp)
    {
        var remaining = comp.NextDispense - _timing.CurTime;
        var ready = remaining <= TimeSpan.Zero;

        DispenseButton.Disabled = !ready || comp.Entries.Count == 0;
        DispenseButton.ToolTip = ready
            ? Loc.GetString("disease-database-ui-dispense-hint")
            : Loc.GetString("disease-database-ui-dispense-cooldown", ("seconds", (int)Math.Ceiling(remaining.TotalSeconds)));
    }

    private void UpdateResearch(DiseaseDatabaseEntry entry)
    {
        // У слабых штаммов скрытых свойств нет, значит и цели исследования тоже: шкала не нужна.
        if (entry.ResearchGoal <= 0)
        {
            ResearchLabel.Text = Loc.GetString("disease-database-ui-research-complete");
            ResearchBar.Visible = false;
            return;
        }

        ResearchBar.Visible = true;
        ResearchBar.MaxValue = entry.ResearchGoal;
        ResearchBar.Value = Math.Min(entry.Research, entry.ResearchGoal);

        ResearchLabel.Text = Loc.GetString("disease-database-ui-research",
            ("research", entry.Research),
            ("goal", entry.ResearchGoal));
    }
}
