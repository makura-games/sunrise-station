using Content.Shared._Sunrise.Disease.Analysis;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Sunrise.Disease;

/// <summary>
/// Карточка пробной партии вакцины: код партии, заявленные свойства и кнопка синтеза.
/// Оформлена как карточки меню обучения.
/// </summary>
/// <remarks>
/// У корня карточки намеренно нет HorizontalExpand и VerticalExpand. GridContainer для
/// растягивающихся ячеек не берёт желаемый размер, а делит своё место поровну между строками
/// и столбцами, и карточка получает меньше, чем намерила: текст свойств перевёрстывается
/// по более узкой ширине, не влезает в отведённую высоту и наезжает на кнопку синтеза.
/// Без этих флагов строка сетки равна самой высокой карточке, и места хватает всегда.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class VaccinatorBatchCard : Control
{
    /// <summary>
    /// Отступ строки свойства от краёв карточки: внешние поля и поля панели.
    /// </summary>
    private const float ClaimInset = 24f;

    /// <summary>
    /// Фон обычной карточки.
    /// </summary>
    private static readonly Color BackgroundColor = new(30, 30, 34);

    /// <summary>
    /// Фон отбракованной карточки: темнее, чтобы она не спорила за внимание с живыми партиями.
    /// </summary>
    private static readonly Color RuledOutColor = new(22, 22, 25);

    /// <summary>
    /// Нажата кнопка синтеза этой партии.
    /// </summary>
    public event Action? OnSynthesizePressed;

    /// <summary>
    /// Отбракована ли показанная партия.
    /// </summary>
    private bool _ruledOut;

    /// <summary>
    /// Как выглядит закрашенное свойство. Длина блоков постоянна для каждой позиции,
    /// поэтому по ней ничего не угадать, а строки не прыгают при обновлении.
    /// </summary>
    private static readonly string[] LockedPatterns =
    [
        "█████ ███ ███████",
        "███████ █████",
        "████ ██████ ███",
        "██████ ████ ██",
    ];

    public VaccinatorBatchCard()
    {
        RobustXamlLoader.Load(this);

        MainPanel.PanelOverride = new StyleBoxFlat(BackgroundColor);
        SynthesizeButton.OnPressed += _ => OnSynthesizePressed?.Invoke();
    }

    /// <summary>
    /// Заполняет карточку данными партии.
    /// </summary>
    /// <param name="candidate">Партия, которую показывает карточка.</param>
    /// <param name="research">Накопленный прогресс исследования штамма.</param>
    /// <param name="costTooltip">Подсказка кнопки синтеза: цена цикла и остаток сырья.</param>
    public void Update(DiseaseVaccineCandidate candidate, int research, string costTooltip)
    {
        _ruledOut = candidate.RuledOut;

        CodeLabel.Text = Loc.GetString("vaccinator-ui-batch", ("code", candidate.Code));
        MainPanel.PanelOverride = new StyleBoxFlat(candidate.RuledOut ? RuledOutColor : BackgroundColor);

        // Перенос строк RichTextLabel считает по MaxWidth. Без него текст меряется в одну строку,
        // а рисуется в несколько и залезает на кнопку, поэтому ширина задаётся явно.
        // Запас перед реальной шириной содержимого обязателен: рисует RichTextLabel по выданной
        // при раскладке ширине, и если она окажется уже измеренной, строк станет больше.
        var claimWidth = (float.IsNaN(SetWidth) ? MinWidth : SetWidth) - ClaimInset;

        ClaimsContainer.RemoveAllChildren();
        for (var i = 0; i < candidate.Lines.Count; i++)
        {
            var line = candidate.Lines[i];
            var locked = line.Text == null;

            var label = new RichTextLabel
            {
                MaxWidth = claimWidth,
                ModulateSelfOverride = candidate.RuledOut || locked ? Color.Gray : null,
            };

            if (locked)
            {
                // Закрашенная строка вместо свойства, а чего не хватает — в подсказке.
                label.SetMessage($"• {LockedPatterns[i % LockedPatterns.Length]}");
                label.MouseFilter = MouseFilterMode.Stop;
                label.ToolTip = BuildLockedTooltip(line, research);
            }
            else
            {
                label.SetMessage($"• {Loc.GetString(line.Text!)}");
            }

            ClaimsContainer.AddChild(label);
        }

        SynthesizeButton.Text = Loc.GetString(candidate.RuledOut
            ? "vaccinator-ui-batch-ruled-out"
            : "vaccinator-ui-batch-synthesize");
        SynthesizeButton.Disabled = candidate.RuledOut;
        SynthesizeButton.ToolTip = costTooltip;
    }

    /// <summary>
    /// Блокирует кнопку, пока машина занята или не хватает сырья.
    /// </summary>
    /// <remarks>
    /// Отдельно от <see cref="Update"/>: окно зовёт это каждый кадр, пока идёт синтез.
    /// </remarks>
    public void SetBlocked(bool blocked)
    {
        SynthesizeButton.Disabled = blocked || _ruledOut;
    }

    /// <summary>
    /// Собирает подсказку закрашенной строки: сколько исследований ещё нужно,
    /// либо пометку, что свойство не читается и при достигнутом прогрессе.
    /// </summary>
    private static string BuildLockedTooltip(DiseaseClaimLine line, int research)
    {
        var missing = line.RevealAt - research;

        return missing > 0
            ? Loc.GetString("vaccinator-ui-claim-locked", ("research", missing))
            : Loc.GetString("vaccinator-ui-claim-unreadable");
    }
}
