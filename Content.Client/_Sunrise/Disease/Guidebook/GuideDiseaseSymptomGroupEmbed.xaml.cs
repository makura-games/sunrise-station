using System.Diagnostics.CodeAnalysis;
using System.Linq;
using Content.Client.Guidebook.Richtext;
using Content.Shared._Sunrise.Disease.Prototypes;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Sunrise.Disease.Guidebook;

/// <summary>
/// Все симптомы болезней подряд: страница собирается из прототипов, а не пишется руками.
/// </summary>
/// <remarks>
/// Необязательный аргумент <c>Beneficial</c> оставляет только полезные или только вредные симптомы.
/// Порядок — от самого лёгкого к самому тяжёлому, внутри одной тяжести по названию.
/// </remarks>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideDiseaseSymptomGroupEmbed : BoxContainer, IDocumentTag
{
    [Dependency] private ILogManager _logManager = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    private readonly ISawmill _sawmill;

    public GuideDiseaseSymptomGroupEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sawmill = _logManager.GetSawmill("guidebook.disease_symptom_group");
        MouseFilter = MouseFilterMode.Stop;
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;

        bool? beneficial = null;
        if (args.TryGetValue("Beneficial", out var raw))
        {
            if (!bool.TryParse(raw, out var parsed))
            {
                _sawmill.Error($"Disease symptom group embed got a non-boolean Beneficial argument \"{raw}\"");
                return false;
            }

            beneficial = parsed;
        }

        var symptoms = _prototype.EnumeratePrototypes<DiseaseSymptomPrototype>()
            .Where(symptom => beneficial == null || symptom.Beneficial == beneficial)
            .OrderBy(symptom => symptom.Severity)
            .ThenBy(symptom => Loc.GetString(symptom.Name));

        foreach (var symptom in symptoms)
        {
            GroupContainer.AddChild(new GuideDiseaseSymptomEmbed(symptom));
        }

        control = this;
        return true;
    }
}
