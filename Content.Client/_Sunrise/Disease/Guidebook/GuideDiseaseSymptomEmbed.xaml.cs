namespace Content.Client._Sunrise.Disease.Guidebook;

/// <summary>
/// Карточка одного симптома болезни в гайдбуке: что он делает с носителем и чего от него ждать.
/// </summary>
/// <remarks>
/// Текст эффектов берётся у самих эффектов, как у реагентов, поэтому страница не разъезжается
/// с прототипами: добавил симптом в YAML — он появился в гайдбуке со своими эффектами.
/// Эффекты без описания для гайдбука пропускаются: у <c>PopupMessage</c> и подобных рассказывать нечего.
/// </remarks>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideDiseaseSymptomEmbed : BoxContainer, IDocumentTag, ISearchableControl, IPrototypeRepresentationControl
{
    [Dependency] private IEntitySystemManager _systemManager = default!;
    [Dependency] private ILogManager _logManager = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    private readonly ISawmill _sawmill;

    /// <summary>Цвет шапки у полезного симптома.</summary>
    private static readonly Color BeneficialColor = Color.FromHex("#3E6B3A");

    /// <summary>Цвет шапки у безвредного симптома.</summary>
    private static readonly Color HarmlessColor = Color.FromHex("#3A4C6B");

    /// <summary>Цвет шапки у самого тяжёлого симптома; к нему ведёт градиент от безвредного.</summary>
    private static readonly Color SevereColor = Color.FromHex("#6B2F2F");

    /// <summary>Тяжесть, на которой шапка окрашена в <see cref="SevereColor"/> целиком.</summary>
    private const float SeverityScale = 4f;

    public IPrototype? RepresentedPrototype { get; private set; }

    public GuideDiseaseSymptomEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sawmill = _logManager.GetSawmill("guidebook.disease_symptom");
        MouseFilter = MouseFilterMode.Stop;
    }

    public GuideDiseaseSymptomEmbed(DiseaseSymptomPrototype symptom) : this()
    {
        GenerateControl(symptom);
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        if (!args.TryGetValue("Symptom", out var id))
        {
            _sawmill.Error("Disease symptom embed tag is missing symptom prototype argument");
            return false;
        }

        if (!_prototype.TryIndex<DiseaseSymptomPrototype>(id, out var symptom))
        {
            _sawmill.Error($"Specified disease symptom prototype \"{id}\" is not a valid symptom prototype");
            return false;
        }

        GenerateControl(symptom);

        control = this;
        return true;
    }

    private void GenerateControl(DiseaseSymptomPrototype symptom)
    {
        RepresentedPrototype = symptom;

        var background = GetHeaderColor(symptom);
        NameBackground.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = background,
        };

        // Текст на тёмной шапке остаётся светлым, на светлой — тёмным, как у карточек реагентов.
        var textColor = 0.2126f * background.R + 0.7152f * background.G + 0.0722f * background.B > 0.5f
            ? Color.Black
            : Color.White;

        SymptomName.SetMarkup(Loc.GetString("guidebook-disease-symptom-name",
            ("color", textColor),
            ("name", Loc.GetString(symptom.Name))));

        var effects = CollectEffects(symptom);
        EffectsContainer.Visible = effects.Count > 0;
        foreach (var effect in effects)
        {
            var label = new RichTextLabel();
            label.SetMarkup(effect);
            EffectsDescriptionContainer.AddChild(label);
        }

        SymptomProperties.SetMessage(BuildProperties(symptom));
    }

    /// <summary>
    /// Описания эффектов симптома: сначала разовые при появлении, затем те, что срабатывают каждый раз.
    /// </summary>
    private List<string> CollectEffects(DiseaseSymptomPrototype symptom)
    {
        var lines = new List<string>();
        AddEffects(lines, symptom.OnsetEffects, "guidebook-disease-symptom-effect-onset");
        AddEffects(lines, symptom.Effects, "guidebook-disease-symptom-effect");
        return lines;
    }

    private void AddEffects(List<string> lines, EntityEffect[]? effects, string format)
    {
        if (effects == null)
            return;

        foreach (var effect in effects)
        {
            string? text;
            try
            {
                text = effect.EntityEffectGuidebookText(_prototype, _systemManager);
            }
            catch (Exception exception)
            {
                // Описание эффекта собирает сам эффект, и сломанная строка локали у него не должна
                // уносить всю страницу: пропускаем и пишем в лог, чей именно эффект виноват.
                _sawmill.Error($"Effect {effect.GetType().Name} failed to describe itself: {exception}");
                continue;
            }

            if (text == null)
                continue;

            lines.Add(Loc.GetString(format, ("effect", text), ("chance", effect.Probability)));
        }
    }

    /// <summary>
    /// Свойства симптома: тяжесть, частота, выброс капель и то, скрывает ли его подавляющее лечение.
    /// </summary>
    private static FormattedMessage BuildProperties(DiseaseSymptomPrototype symptom)
    {
        var message = new FormattedMessage();
        message.AddMarkupOrThrow(Loc.GetString("guidebook-disease-symptom-severity",
            ("severity", symptom.Severity),
            ("beneficial", symptom.Beneficial)));

        if (symptom.Probability < 1f)
        {
            message.PushNewline();
            message.AddMarkupOrThrow(Loc.GetString("guidebook-disease-symptom-probability",
                ("chance", symptom.Probability)));
        }

        if (symptom.Spread is { } spread)
        {
            message.PushNewline();
            message.AddMarkupOrThrow(Loc.GetString("guidebook-disease-symptom-spread",
                ("range", spread.Range),
                ("chance", spread.Chance)));
        }

        message.PushNewline();
        message.AddMarkupOrThrow(Loc.GetString(symptom.Suppressible
            ? "guidebook-disease-symptom-suppressible"
            : "guidebook-disease-symptom-stubborn"));

        return message;
    }

    /// <summary>
    /// Цвет шапки: полезные симптомы зелёные, вредные тем краснее, чем тяжелее.
    /// </summary>
    private static Color GetHeaderColor(DiseaseSymptomPrototype symptom)
    {
        if (symptom.Beneficial)
            return BeneficialColor;

        var weight = Math.Clamp(symptom.Severity / SeverityScale, 0f, 1f);
        return Color.InterpolateBetween(HarmlessColor, SevereColor, weight);
    }
}
