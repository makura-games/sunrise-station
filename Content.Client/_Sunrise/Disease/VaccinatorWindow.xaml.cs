using Content.Shared._Sunrise.Disease.Components;
using Content.Shared._Sunrise.Disease.Vaccinator;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client._Sunrise.Disease;

/// <summary>
/// Окно вакцинатора: пробные партии вакцины, производство по найденному рецепту
/// и выделение сыворотки из крови донора.
/// Данные анализов машина не показывает — их игрок читает по распечаткам диагностера.
/// </summary>
/// <remarks>
/// Окно рисуется из состояния компонента машины. Обратный отсчёт синтеза идёт по локальным часам:
/// сервер присылает только момент окончания, а тикает таймер уже клиент.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class VaccinatorWindow : FancyWindow
{
    private readonly IGameTiming _timing;

    /// <summary>
    /// Карточки партий в том же порядке, в каком они пришли в состоянии.
    /// </summary>
    private readonly List<VaccinatorBatchCard> _cards = [];

    /// <summary>
    /// Кнопки выделения сыворотки.
    /// </summary>
    private readonly List<Button> _serumButtons = [];

    private Entity<VaccinatorComponent>? _vaccinator;

    /// <summary>
    /// Выбрана партия для синтеза. Передаётся её индекс в списке.
    /// </summary>
    public event Action<int>? OnSynthesizePressed;

    /// <summary>
    /// Запрошена ещё одна доза по уже найденному рецепту.
    /// </summary>
    public event Action? OnProducePressed;

    /// <summary>
    /// Выбран штамм для выделения сыворотки. Передаётся индекс варианта.
    /// </summary>
    public event Action<int>? OnExtractSerumPressed;

    public VaccinatorWindow()
    {
        RobustXamlLoader.Load(this);

        _timing = IoCManager.Resolve<IGameTiming>();
        ProduceButton.OnPressed += _ => OnProducePressed?.Invoke();
    }

    public void UpdateState(Entity<VaccinatorComponent> vaccinator)
    {
        _vaccinator = vaccinator;

        var comp = vaccinator.Comp;

        // Цена цикла и остаток сырья живут в подсказке кнопок, а не отдельной строкой в окне.
        var trialTooltip = Loc.GetString("vaccinator-ui-cost-tooltip",
            ("cost", comp.TrialCost),
            ("amount", comp.MaterialAmount));

        var productionTooltip = Loc.GetString("vaccinator-ui-cost-tooltip",
            ("cost", comp.ProductionCost),
            ("amount", comp.MaterialAmount));

        ProduceButton.ToolTip = productionTooltip;

        UpdateResearch(comp, trialTooltip);
        UpdateSerum(comp, productionTooltip);
        UpdateBusy(comp);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // Таймер синтеза отсчитывается локально, поэтому цифры идут плавно и без сетевых посылок.
        if (_vaccinator is { } vaccinator)
            UpdateBusy(vaccinator.Comp);
    }

    /// <summary>
    /// Пересобирает список партий и блок производства.
    /// </summary>
    private void UpdateResearch(VaccinatorComponent comp, string costTooltip)
    {
        BatchContainer.RemoveAllChildren();
        _cards.Clear();

        // Код штамма стоит в заголовке раздела: отдельной строки под него в окне нет.
        BatchHeaderLabel.Text = comp.HasSample
            ? Loc.GetString("vaccinator-ui-batches-header-strain", ("strain", comp.StrainCode))
            : Loc.GetString("vaccinator-ui-batches-header");

        ProductionHeaderLabel.Text = comp.HasSample
            ? Loc.GetString("vaccinator-ui-production-header-strain", ("strain", comp.StrainCode))
            : Loc.GetString("vaccinator-ui-production-header");

        // Найденный рецепт убирает перебор: дальше машина штампует дозы по нему.
        if (comp.HasSample && comp.SolvedCode is { } solvedCode)
        {
            ProductionBlock.Visible = true;
            BatchBlock.Visible = false;
            ProductionHintLabel.Text = Loc.GetString("vaccinator-ui-production-hint", ("code", solvedCode));
            return;
        }

        ProductionBlock.Visible = false;
        BatchBlock.Visible = true;

        // Без образца или без данных анализов партий нет, но место под них остаётся занятым:
        // иначе два разделителя сходятся вплотную и окно выглядит сломанным.
        if (comp.Candidates.Count == 0)
        {
            BatchScroll.Visible = false;
            BatchPlaceholderLabel.Visible = true;
            BatchPlaceholderLabel.Text = GetPlaceholderText(comp);
            return;
        }

        BatchPlaceholderLabel.Visible = false;
        BatchScroll.Visible = true;

        for (var i = 0; i < comp.Candidates.Count; i++)
        {
            var index = i;
            var card = new VaccinatorBatchCard();
            card.Update(comp.Candidates[i], comp.Research, costTooltip);
            card.OnSynthesizePressed += () => OnSynthesizePressed?.Invoke(index);

            _cards.Add(card);
            BatchContainer.AddChild(card);
        }
    }

    /// <summary>
    /// Объясняет, почему партий нет и что с этим делать.
    /// </summary>
    private static string GetPlaceholderText(VaccinatorComponent comp)
    {
        if (!comp.HasSample)
            return Loc.GetString("vaccinator-ui-batches-no-sample");

        // Дела ещё нет: образец никто не относил в диагностер.
        if (!comp.HasData)
            return Loc.GetString("vaccinator-ui-batches-no-data");

        // Дело есть, но подтверждённых фактов мало на такой штамм.
        return Loc.GetString("vaccinator-ui-batches-not-enough", ("facts", Math.Max(comp.MissingFacts, 1)));
    }

    private void UpdateSerum(VaccinatorComponent comp, string costTooltip)
    {
        SerumContainer.RemoveAllChildren();
        _serumButtons.Clear();

        SerumHintLabel.Text = comp.SerumStatus switch
        {
            DiseaseSerumStatus.NoBlood => Loc.GetString("vaccinator-ui-serum-no-blood"),
            DiseaseSerumStatus.NotEnoughBlood => Loc.GetString("vaccinator-ui-serum-not-enough",
                ("amount", comp.BloodCost)),
            DiseaseSerumStatus.UnknownDonor => Loc.GetString("vaccinator-ui-serum-unknown-donor"),
            DiseaseSerumStatus.Ready => Loc.GetString("vaccinator-ui-serum-ready"),
            _ => Loc.GetString("vaccinator-ui-serum-empty"),
        };

        for (var i = 0; i < comp.SerumOptions.Count; i++)
        {
            var index = i;
            var button = new Button
            {
                Text = Loc.GetString("vaccinator-ui-serum-button", ("strain", comp.SerumOptions[i])),
                ToolTip = costTooltip,
                HorizontalExpand = true,
            };
            button.OnPressed += _ => OnExtractSerumPressed?.Invoke(index);

            _serumButtons.Add(button);
            SerumContainer.AddChild(button);
        }
    }

    /// <summary>
    /// Обновляет строку состояния и блокировки кнопок.
    /// </summary>
    /// <remarks>
    /// Зовётся каждый кадр, поэтому тут только текст и флаги: пересборка списков здесь недопустима.
    /// </remarks>
    private void UpdateBusy(VaccinatorComponent comp)
    {
        var remaining = comp.FinishAt is { } finishAt ? finishAt - _timing.CurTime : TimeSpan.Zero;
        var busy = remaining > TimeSpan.Zero;
        var seconds = (int)Math.Ceiling(remaining.TotalSeconds);

        var status = busy
            ? Loc.GetString(comp.Cleaning ? "vaccinator-ui-cleaning" : "vaccinator-ui-busy", ("seconds", seconds))
            : string.Empty;

        // В режиме производства состояние цикла показывается по центру блока, а не строкой наверху:
        // иначе отсчёт идёт в одном углу окна, а кнопка, к которой он относится, — в другом.
        var production = ProductionBlock.Visible;

        StatusLabel.Visible = busy && !production;
        if (busy && !production)
            StatusLabel.Text = status;

        if (production)
        {
            ProductionStatusLabel.Text = busy
                ? status
                : Loc.GetString("vaccinator-ui-production-note");
        }

        ProduceButton.Disabled = busy || comp.MaterialAmount < comp.ProductionCost;

        var trialBlocked = busy || comp.MaterialAmount < comp.TrialCost;
        foreach (var card in _cards)
        {
            card.SetBlocked(trialBlocked);
        }

        foreach (var button in _serumButtons)
        {
            button.Disabled = busy || comp.MaterialAmount < comp.ProductionCost;
        }
    }
}
