    private void SelectTool(DiseaseMicroscopeTool tool)
    {
        CultureField.Tool = tool;
        foreach (var (candidate, button) in _tools)
            button.Pressed = candidate == tool;

        UpdateToolTips();
        UpdateEnabled();
        UpdatePreview();
    }

    private void UpdateEnabled()
    {
        if (_microscope is not { } microscope)
            return;

        var ready = microscope.Powered && microscope.HasSample && !_pending;
        var running = IsMatchRunning(microscope);
        SampleButton.Disabled = _pending;
        UpdateTransmission(microscope, ready, running);
        SymptomSelector.Disabled = !ready || microscope.StageOptions.Count == 0;
        var options = microscope.StageOpen ? 1 : 2;
        PrepareButton.Disabled = !ready || microscope.StageOptions.Count < options || !microscope.Profile.IsValid ||
                                 microscope.NutrientUnits < microscope.PrepareCost;
        AdvanceButton.Disabled = !ready || running;
        FinishButton.Disabled = !ready || !running;
        // Надпись не меняется от состояния: длинный текст не влезал в ряд инструментов.
        // Что прогноз уже оплачен, видно по заблокированной кнопке, строке результата и подсказке.
        ForecastButton.Text = _loc.GetString("disease-microscope-forecast", ("left", microscope.ForecastsLeft));
        ForecastButton.Disabled = !ready || !running || microscope.ForecastActive || microscope.ForecastsLeft <= 0 ||
                                  microscope.InhibitorUnits < Math.Max(1, (int)microscope.Profile.InhibitorCost);
        ProduceButton.Disabled = !ready || microscope.Genome.Count == 0;
        foreach (var (_, button) in _tools)
            button.Disabled = !ready || !running;

        CultureField.InteractionEnabled = ready && running;

        var feedback = _pending ? "disease-microscope-waiting"
            : !microscope.Powered ? "disease-microscope-feedback-unpowered"
            : !microscope.HasSample ? "disease-microscope-feedback-invalid-sample"
            : microscope.Feedback;
        StatusLabel.Text = _loc.GetString(feedback);
        StatusLabel.ModulateSelfOverride = Problems.Contains(feedback) ? Palettes.Red.Base
            : Successes.Contains(feedback) ? Palettes.Green.Base
            : null;
    }

    /// <summary>
    /// Панель путей передачи: развитые пути остаются нажатыми, остальные можно разыграть отдельной партией.
    /// </summary>
    private void UpdateTransmission(DiseaseMicroscopeComponent microscope, bool ready, bool running)
    {
        TransmissionPanel.Visible = microscope.TransmissionUnlocked && !running;
        if (!TransmissionPanel.Visible)
            return;

        var affordable = microscope.NutrientUnits >= microscope.PrepareCost;
        foreach (var (route, button) in _routes)
        {
            var developed = (microscope.Routes & route) != 0;
            button.Pressed = developed;
            button.Disabled = !ready || developed || !affordable;
        }
    }

    /// <summary>
    /// Подсказка заголовка путей: как работает селекция и какие пути уже закреплены в штамме.
    /// </summary>
    private string GetTransmissionHint()
    {
        // Внутривенный путь есть у любого штамма: с него начинается список развитых.
        var routeNames = new List<string> { RouteName(DiseaseTransmissionRoute.Injection) };
        if (_microscope is { } microscope)
        {
            foreach (var (route, _) in _routes)
            {
                if ((microscope.Routes & route) != 0)
                    routeNames.Add(RouteName(route));
            }
        }

        return _loc.GetString("disease-microscope-routes-hint") + "\n" +
               _loc.GetString("disease-microscope-routes", ("routes", string.Join(", ", routeNames)));
    }

    /// <summary>Подсказка кнопки пути: цена партии или отметка, что путь уже закреплён.</summary>
    private string GetRouteHint(DiseaseTransmissionRoute route)
    {
        if (_microscope is { } microscope && (microscope.Routes & route) != 0)
            return _loc.GetString("disease-microscope-route-developed-hint");

        return _loc.GetString("disease-microscope-route-hint", ("cost", _microscope?.PrepareCost ?? 0));
    }

    /// <summary>Цель партии: путь передачи или симптом стадии.</summary>
    private string GetTargetName(DiseaseMicroscopeComponent microscope)
    {
        if (microscope.TargetRoute != DiseaseTransmissionRoute.None)
            return RouteName(microscope.TargetRoute);

        return microscope.TargetSymptom is { } symptom ? SymptomName(symptom) : string.Empty;
    }

    /// <summary>Конкурент партии: за путь передачи играет нестабильная культура, а не симптом.</summary>
    private string GetRivalName(DiseaseMicroscopeComponent microscope)
    {
        if (microscope.TargetRoute != DiseaseTransmissionRoute.None)
            return _loc.GetString("disease-microscope-route-rival");

        return microscope.RivalSymptom is { } symptom ? SymptomName(symptom) : string.Empty;
    }

    private void UpdateSelector(IReadOnlyList<ProtoId<DiseaseSymptomPrototype>> symptoms)
    {
        var changed = symptoms.Count != _stageOptions.Count;
        for (var i = 0; !changed && i < symptoms.Count; i++)
            changed = symptoms[i] != _stageOptions[i];
        if (!changed)
            return;

        _stageOptions.Clear();
        SymptomSelector.Clear();
        for (var i = 0; i < symptoms.Count; i++)
        {
            _stageOptions.Add(symptoms[i]);
            SymptomSelector.AddItem(SymptomName(symptoms[i]), i);
        }

        if (symptoms.Count > 0)
            SymptomSelector.SelectId(0);
    }

    /// <summary>
    /// Красит рамку инструмента по тому, что даст ход. Текстом это не дублируется:
    /// подсказка под курсором мешала бы читать поле.
    /// </summary>
    private void UpdatePreview()
    {
        if (_microscope is not { } microscope || CultureField.HoveredCell == null ||
            microscope.Cells.Length != DiseaseCultureBoard.CellCount)
        {
            CultureField.PreviewState = DiseaseCulturePreview.Neutral;
            return;
        }

        var nutrient = CultureField.Tool == DiseaseMicroscopeTool.Nutrient;
        var changed = false;
        var side = false;
        foreach (var colony in new[] { DiseaseCultureBoard.Target, DiseaseCultureBoard.Opponent })
        {
            var before = DiseaseCultureBoard.CountColony(CultureField.Cells, colony);
            var delta = DiseaseCultureBoard.CountColony(CultureField.Preview, colony) - before;
            if (delta == 0)
                continue;

            changed = true;

            // Рост конкурента и потеря цели — побочные эффекты, из-за которых рамка желтеет.
            side |= colony == DiseaseCultureBoard.Opponent && delta > 0 ||
                    colony == DiseaseCultureBoard.Target && delta < 0;
        }

        // Выжигание среды — тоже изменение поля, иначе оценка разошлась бы с решением машины.
        for (var i = 0; !changed && i < CultureField.Preview.Count && i < CultureField.Cells.Count; i++)
            changed = CultureField.Preview[i] == DiseaseCultureBoard.Sterile &&
                      CultureField.Cells[i] != DiseaseCultureBoard.Sterile;

        var cost = Math.Max(1, (int)(nutrient ? microscope.Profile.NutrientCost : microscope.Profile.InhibitorCost));
        var units = nutrient ? microscope.NutrientUnits : microscope.InhibitorUnits;
        CultureField.PreviewState = !changed || units < cost
            ? DiseaseCulturePreview.Blocked
            : side
                ? DiseaseCulturePreview.Caution
                : DiseaseCulturePreview.Allowed;
    }

    private string SymptomName(ProtoId<DiseaseSymptomPrototype> symptom)
    {
        return _prototype.TryIndex(symptom, out var prototype) ? _loc.GetString(prototype.Name) : symptom.Id;
    }

    private string RouteName(DiseaseTransmissionRoute route)
    {
        return _loc.GetString(route switch
        {
            DiseaseTransmissionRoute.Contact => "disease-microscope-route-contact",
            DiseaseTransmissionRoute.Ingestion => "disease-microscope-route-ingestion",
            DiseaseTransmissionRoute.Droplet => "disease-microscope-route-droplet",
            _ => "disease-microscope-route-injection",
        });
    }
