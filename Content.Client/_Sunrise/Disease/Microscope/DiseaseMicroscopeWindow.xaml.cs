    /// <summary>Обновляет окно по реплицированному состоянию машины.</summary>
    public void UpdateState(DiseaseMicroscopeComponent microscope, bool pending)
    {
        _microscope = microscope;
        _pending = pending;
        SampleLabel.Text = _loc.GetString(microscope.HasSample ? "disease-microscope-sample" : "disease-microscope-no-sample",
            ("strain", microscope.StrainCode));
        SampleButton.Text = _loc.GetString(microscope.SampleInserted ? "disease-microscope-eject" : "disease-microscope-insert");

        SampleView.SetEntity(microscope.SampleView is { } view ? _entities.GetEntity(view) : null);
        UpdateGenome(microscope);
        UpdateSelector(microscope.StageOptions);
        CultureField.Profile = microscope.Profile;
        CultureField.SetCells(microscope.Cells);
        CultureField.SetForecast(microscope.ForecastActive, microscope.Turn);
        CultureField.SetOpponentMoves(microscope.OpponentMoves);
        UpdateMatch(microscope);
        UpdateReservoir(microscope);
        UpdateToolTips();

        UpdateEnabled();
        UpdatePreview();
    }

