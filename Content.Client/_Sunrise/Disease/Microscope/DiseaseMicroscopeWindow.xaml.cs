    private DiseaseCultureProfile Profile => _microscope?.Profile ?? DiseaseCultureProfile.Empty;

    private static bool IsMatchRunning(DiseaseMicroscopeComponent microscope)
    {
        return microscope.Cells.Length == DiseaseCultureBoard.CellCount &&
               (microscope.TargetSymptom != null || microscope.TargetRoute != DiseaseTransmissionRoute.None);
    }

    /// <summary>Собирает правила текущей стадии для подсказок.</summary>
    private string GetStageRules(DiseaseCultureProfile profile)
    {
        if (!profile.IsValid)
            return string.Empty;

        // Все отличия стадии собраны в одну подсказку, чтобы игрок не выяснял правила методом проб.
        var rules = new List<string>
        {
            _loc.GetString("disease-microscope-rule-growth", ("growth", profile.RequiredGrowth)),
            _loc.GetString("disease-microscope-rule-share", ("share", profile.RequiredShare)),
            _loc.GetString("disease-microscope-rule-moves", ("moves", profile.OpponentMoves)),
            _loc.GetString("disease-microscope-rule-cost",
                ("nutrient", profile.NutrientCost),
                ("inhibitor", profile.InhibitorCost)),
            _loc.GetString("disease-microscope-rule-sterile"),
            _loc.GetString("disease-microscope-rule-spore"),
        };
        if (profile.OpponentDisplace)
            rules.Add(_loc.GetString("disease-microscope-rule-displace"));
        if (profile.TargetCross)
            rules.Add(_loc.GetString("disease-microscope-rule-cross"));
        if (profile.ResilientOpponent)
            rules.Add(_loc.GetString("disease-microscope-rule-resilient"));
        if (profile.NarrowInhibitor)
            rules.Add(_loc.GetString("disease-microscope-rule-narrow"));
        if (profile.OpponentToxin)
            rules.Add(_loc.GetString("disease-microscope-rule-toxin"));

        return string.Join("\n", rules);
    }

    /// <summary>Рисует геном: развитые стадии с весами, текущую и ещё не начатые.</summary>
    private void UpdateGenome(DiseaseMicroscopeComponent microscope)
    {
        var nodes = new List<DiseaseGenomeStrip.StageNode>(Math.Max(microscope.MaxStage, microscope.Genome.Count));
        for (var stage = 0; stage < microscope.MaxStage; stage++)
        {
            if (stage < microscope.Genome.Count)
            {
                var pool = microscope.Genome[stage];
                var open = microscope.StageOpen && stage == microscope.Genome.Count - 1;
                nodes.Add(new DiseaseGenomeStrip.StageNode(true, _loc.GetString(
                    open ? "disease-microscope-genome-open" : "disease-microscope-genome-done",
                    ("stage", stage + 1),
                    ("symptom", GetStageSymptoms(pool)))));
                continue;
            }

            var current = stage == microscope.Stage && !microscope.StageOpen;
            nodes.Add(new DiseaseGenomeStrip.StageNode(false, _loc.GetString(
                current ? "disease-microscope-genome-current" : "disease-microscope-genome-locked",
                ("stage", stage + 1))));
        }

        GenomeStrip.SetGenome(nodes, microscope.StageOpen ? microscope.Stage - 1 : microscope.Stage);
        GenomeStrip.Visible = microscope.MaxStage > 0;
    }

    /// <summary>Симптомы стадии в порядке развития: у носителя проявляются все.</summary>
    private string GetStageSymptoms(DiseaseStagePool pool)
    {
        var names = new List<string>(pool.Symptoms.Count);
        foreach (var entry in pool.Symptoms)
            names.Add(SymptomName(entry.Symptom));

        return string.Join(", ", names);
    }

    /// <summary>
    /// Числа партии живут в подсказке шкалы: на самой шкале стоит только метка требования,
    /// иначе окуляр соседствовал бы с колонкой цифр.
    /// </summary>
    private string GetGaugeHint()
    {
        if (_microscope is not { } microscope || !IsMatchRunning(microscope))
            return _loc.GetString("disease-microscope-gauge-hint");

        var target = DiseaseCultureBoard.CountColony(microscope.Cells, DiseaseCultureBoard.Target);
        var rival = DiseaseCultureBoard.CountColony(microscope.Cells, DiseaseCultureBoard.Opponent);

        // Строки собраны списком, а не параметрами: params-перегрузка не проходит проверку IL движка.
        var lines = new List<string>
        {
            _loc.GetString("disease-microscope-gauge-hint"),
            _loc.GetString("disease-microscope-gauge-growth",
                ("count", target),
                ("growth", microscope.Profile.RequiredGrowth)),
            _loc.GetString("disease-microscope-gauge-share",
                ("share", DiseaseCultureProfile.GetShare(target, rival)),
                ("required", microscope.Profile.RequiredShare)),
            _loc.GetString("disease-microscope-gauge-mark",
                ("required", Math.Max(1, microscope.Profile.GetRequiredTarget(rival)))),
        };

        return string.Join("\n", lines);
    }

    /// <summary>Переключает правую колонку между выбором цели и идущей партией.</summary>
    private void UpdateMatch(DiseaseMicroscopeComponent microscope)
    {
        var running = IsMatchRunning(microscope);
        MatchPanel.Visible = running;
        SetupPanel.Visible = !running && microscope.Profile.IsValid;
        SetupHeader.Text = microscope.StageOpen
            ? _loc.GetString("disease-microscope-reinforce", ("left", microscope.ReinforcementsLeft))
            : _loc.GetString("disease-microscope-target");
        PrepareButton.Text = _loc.GetString(microscope.StageOpen
            ? "disease-microscope-prepare-bonus"
            : "disease-microscope-prepare");
        AdvanceButton.Visible = microscope.StageOpen;
        AdvanceButton.Text = _loc.GetString(microscope.Stage >= microscope.MaxStage
            ? "disease-microscope-advance-last"
            : "disease-microscope-advance");

        if (!running)
            return;

        var target = DiseaseCultureBoard.CountColony(microscope.Cells, DiseaseCultureBoard.Target);
        var rival = DiseaseCultureBoard.CountColony(microscope.Cells, DiseaseCultureBoard.Opponent);

        // Оба условия стадии сведены к одному числу клеток, поэтому и счётчик, и метка на шкале одни.
        var required = Math.Max(1, microscope.Profile.GetRequiredTarget(rival));

        // Партия за путь передачи не привязана к стадии генома, поэтому заголовок называет путь.
        var routeMatch = microscope.TargetRoute != DiseaseTransmissionRoute.None;
        StageLabel.Text = routeMatch
            ? _loc.GetString("disease-microscope-route-stage", ("route", RouteName(microscope.TargetRoute)))
            : _loc.GetString("disease-microscope-stage",
                ("stage", microscope.Stage + 1),
                ("stages", microscope.MaxStage));
        StageLabel.ModulateSelfOverride = DiseaseMicroscopePalette.Tier(microscope.Profile.Tier);

        // Сторону задают место и цвет: ваш счёт у левого края, счёт конкурента — у правого.
        var growth = microscope.Profile.IsGrowthReached(target);
        var share = microscope.Profile.IsShareReached(target, rival);
        TargetLabel.Text = _loc.GetString("disease-microscope-match-target",
            ("symptom", GetTargetName(microscope)),
            ("count", target),
            ("required", required));
        TargetLabel.ModulateSelfOverride = growth && share
            ? DiseaseMicroscopePalette.Colony(DiseaseCultureBoard.Target)
            : null;

        RivalLabel.Text = _loc.GetString("disease-microscope-match-rival",
            ("symptom", GetRivalName(microscope)),
            ("count", rival));
        RivalLabel.ModulateSelfOverride = DiseaseMicroscopePalette.Colony(DiseaseCultureBoard.Opponent);

        MatchGauge.SetScore(target, rival, required);

        DiseaseTooltip.Attach(FinishButton,
            _loc.GetString("disease-microscope-finish"),
            _loc.GetString(!growth ? "disease-microscope-finish-hint-short"
                : !share ? "disease-microscope-finish-hint-share"
                : "disease-microscope-finish-hint-ready"));
    }

    /// <summary>Резервуар показан заполненностью, а расход — числом рядом с названием реагента.</summary>
    private void UpdateReservoir(DiseaseMicroscopeComponent microscope)
    {
        var capacity = Math.Max(1, microscope.ReservoirCapacity);
        var nutrientCost = Math.Max(1, (int)microscope.Profile.NutrientCost);
        var inhibitorCost = Math.Max(1, (int)microscope.Profile.InhibitorCost);

        NutrientLabel.Text = _loc.GetString("disease-microscope-nutrient",
            ("units", microscope.NutrientUnits),
            ("capacity", capacity));
        NutrientCostLabel.Text = _loc.GetString("disease-microscope-cost", ("cost", nutrientCost));
        NutrientBar.Value = Math.Min(1f, (float)microscope.NutrientUnits / capacity);
        NutrientBar.ModulateSelfOverride = microscope.NutrientUnits < nutrientCost
            ? Palettes.Red.Base
            : DiseaseMicroscopePalette.Colony(DiseaseCultureBoard.Target);

        InhibitorLabel.Text = _loc.GetString("disease-microscope-inhibitor",
            ("units", microscope.InhibitorUnits),
            ("capacity", capacity));
        InhibitorCostLabel.Text = _loc.GetString("disease-microscope-cost", ("cost", inhibitorCost));
        InhibitorBar.Value = Math.Min(1f, (float)microscope.InhibitorUnits / capacity);
        InhibitorBar.ModulateSelfOverride = microscope.InhibitorUnits < inhibitorCost
            ? Palettes.Red.Base
            : DiseaseMicroscopePalette.Removed;
    }

