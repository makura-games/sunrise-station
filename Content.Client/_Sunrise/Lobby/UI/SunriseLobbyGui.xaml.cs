    public SunriseLobbyGui()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        SetAnchorPreset(MainContainer, LayoutPreset.Wide);
        SetAnchorPreset(LobbyArt, LayoutPreset.Wide);
        SetAnchorPreset(LobbyAnimation, LayoutPreset.Wide);

        LobbySong.SetMarkup(_loc.GetString("lobby-state-song-no-song-text"));

        LeaveButton.OnPressed += _ => _console.ExecuteCommand("disconnect");
        OptionsButton.OnPressed += _ => UserInterfaceManager.GetUIController<OptionsUIController>().ToggleWindow();

        Offset = new Vector2(_random.Next(0, 1000), _random.Next(0, 1000));
        RectClipContent = true;

        var panelTex = _resource.GetTexture("/Textures/Interface/Nano/button.svg.96dpi.png");
        _back = new StyleBoxTexture
        {
            Texture = panelTex,
            Modulate = new Color(37, 37, 42),
        };
        _back.SetPatchMargin(StyleBox.Margin.All, 10);

        LeftTopPanel.PanelOverride = _back;

        RightPanel.PanelOverride = _back;

        LeftBottomPanel.PanelOverride = _back;

        LeftTopPanel.PanelOverride = _back;

        LobbySongPanel.PanelOverride = _back;

        SocialButtonsPanel.PanelOverride = _back;

        Chat.SetChatOpacity();
        Chat.ToggleEmojiButton(true);

        ServerName.Text = _loc.GetString("ui-lobby-welcome", ("name", _serverName));

        LoadIcons();
        SetupButtonsIcons();
        SetupButtonsBinding();

        StationTime.Parent?.RemoveChild(StationTime);
        ServerInfo.AddStationTime(StationTime);
        RestoreCollapsedStates();
    }


