    public void SetupHeaderHoverAndClick(Control header, TextureRect hiderIcon, Action toggleAction)
    {
        header.MouseFilter = MouseFilterMode.Stop;

        header.OnMouseEntered += _ =>
        {
            hiderIcon.Modulate = Color.White;
            PlayHoverSound();
        };

        header.OnMouseExited += _ =>
        {
            hiderIcon.Modulate = Palettes.Gold.Base;
        };

        header.OnKeyBindUp += args =>
        {
            if (args.Function != EngineKeyFunctions.Use)
                return;

            PlayClickSound();
            toggleAction();
        };
    }

