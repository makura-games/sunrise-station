using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Sunrise.Paint.UI;

[GenerateTypedNameReferences]
public sealed partial class PaintColorWindow : FancyWindow
{
    public event Action<Color>? OnApplyButtonPressed;

    public PaintColorWindow()
    {
        RobustXamlLoader.Load(this);

        ColorSelector.OnColorChanged += color => ColorPreview.ModulateSelfOverride = color;
        ApplyButton.OnPressed += _ => OnApplyButtonPressed?.Invoke(ColorSelector.Color);
    }

    public void SetColor(Color color)
    {
        ColorSelector.Color = color.WithAlpha(1f);
        ColorPreview.ModulateSelfOverride = ColorSelector.Color;
    }
}
