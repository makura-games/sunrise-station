using System.Numerics;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Sunrise.Paint.UI;

[GenerateTypedNameReferences]
public sealed partial class PaintColorWindow : FancyWindow
{
    public event Action<Color>? OnApplyButtonPressed;

    private readonly StyleBoxFlat _colorPreviewStyle = new();

    private Color _color = Color.White;

    public PaintColorWindow()
    {
        RobustXamlLoader.Load(this);

        HueSlider.BackgroundStyleBoxOverride = new ColorSelectorStyleBox(ColorSelectorStyleBox.ColorSliderPreset.Hue);
        ColorPreview.PanelOverride = _colorPreviewStyle;

        RedInput.IsValid = IsRgbValue;
        GreenInput.IsValid = IsRgbValue;
        BlueInput.IsValid = IsRgbValue;
        HexInput.IsValid = IsPotentialHex;

        SaturationValueSelector.OnValueChanged += OnSaturationValueChanged;
        HueSlider.OnValueChanged += _ => OnHueChanged();
        RedInput.ValueChanged += _ => OnRgbChanged();
        GreenInput.ValueChanged += _ => OnRgbChanged();
        BlueInput.ValueChanged += _ => OnRgbChanged();
        HexInput.OnTextChanged += OnHexChanged;
        HexInput.OnTextEntered += OnHexCommitted;
        HexInput.OnFocusExit += OnHexCommitted;
        ApplyButton.OnPressed += _ => OnApplyPressed();

        SetColor(_color);
    }

    public Color Color
    {
        set => SetColor(value);
    }

    private void OnSaturationValueChanged()
    {
        SetColorFromHsv(
            HueSlider.Value,
            SaturationValueSelector.Saturation,
            SaturationValueSelector.Value);
    }

    private void OnHueChanged()
    {
        SaturationValueSelector.SetHue(HueSlider.Value);
        SetColorFromHsv(
            HueSlider.Value,
            SaturationValueSelector.Saturation,
            SaturationValueSelector.Value);
    }

    private void OnRgbChanged() =>
        SetColor(new Color((byte)RedInput.Value, (byte)GreenInput.Value, (byte)BlueInput.Value));

    private void OnHexChanged(LineEdit.LineEditEventArgs args)
    {
        if (!TryParseHex(args.Text, out var color, allowShorthand: false))
            return;

        SetColor(color);
    }

    private void OnHexCommitted(LineEdit.LineEditEventArgs args)
    {
        if (TryParseHex(args.Text, out var color))
            SetColor(color);
        else
            HexInput.Text = _color.ToHexNoAlpha();
    }

    private void OnApplyPressed()
    {
        if (TryParseHex(HexInput.Text, out var color))
            SetColor(color);

        OnApplyButtonPressed?.Invoke(_color);
    }

    private void SetColorFromHsv(float hue, float saturation, float value)
    {
        _color = Color.FromHsv(new Vector4(hue, saturation, value, 1f));
        UpdateInputs();
    }

    private void SetColor(Color color)
    {
        _color = new Color(color.R, color.G, color.B);

        var hsv = Color.ToHsv(_color);
        HueSlider.SetValueWithoutEvent(hsv.X);
        SaturationValueSelector.SetColor(hsv);
        UpdateInputs();
    }

    private void UpdateInputs()
    {
        RedInput.OverrideValue(_color.RByte);
        GreenInput.OverrideValue(_color.GByte);
        BlueInput.OverrideValue(_color.BByte);
        HexInput.Text = _color.ToHexNoAlpha();
        _colorPreviewStyle.BackgroundColor = _color;
    }

    private static bool IsRgbValue(int value)
    {
        return value is >= 0 and <= byte.MaxValue;
    }

    // * Hex
    private static bool IsPotentialHex(string value)
    {
        if (value.Length > 7)
            return false;

        for (var i = 0; i < value.Length; i++)
        {
            if (i == 0 && value[i] == '#')
                continue;

            if (!Uri.IsHexDigit(value[i]))
                return false;
        }

        return true;
    }

    private static bool TryParseHex(string value, out Color color, bool allowShorthand = true)
    {
        var normalized = value.StartsWith('#') ? value : $"#{value}";
        // Стандарт 7
        var parsed = allowShorthand || normalized.Length == 7
            ? Color.TryFromHex(normalized)
            : null;
        color = parsed ?? default;
        return parsed != null;
    }
}
